-- =========================================================
CREATE TABLE public.invoice_status_history (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  invoice_id uuid NOT NULL REFERENCES public.invoices(id) ON DELETE CASCADE,
  from_status public.record_status,
  to_status public.record_status NOT NULL,
  note text,
  actor_id uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT, INSERT ON public.invoice_status_history TO authenticated;
GRANT ALL ON public.invoice_status_history TO service_role;
ALTER TABLE public.invoice_status_history ENABLE ROW LEVEL SECURITY;

CREATE INDEX invoice_status_history_invoice_idx ON public.invoice_status_history (invoice_id);

CREATE POLICY "invoice_history_select_scoped" ON public.invoice_status_history
  FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.invoices i
    WHERE i.id = invoice_status_history.invoice_id
      AND (public.is_accountant() OR public.can_access_project(i.project_id))
  ));

CREATE POLICY "invoice_history_insert_scoped" ON public.invoice_status_history
  FOR INSERT TO authenticated
  WITH CHECK (
    actor_id = auth.uid()
    AND EXISTS (
      SELECT 1 FROM public.invoices i
      WHERE i.id = invoice_status_history.invoice_id
        AND (public.is_accountant() OR public.can_access_project(i.project_id))
    )
    AND (public.is_accountant() OR to_status IN ('draft', 'under_review'))
  );

