-- 5) CUSTODY <-> INVOICE SETTLEMENT
-- =========================================================
ALTER TABLE public.custody_transactions
  ADD COLUMN invoice_id uuid REFERENCES public.invoices(id);

CREATE INDEX custody_transactions_invoice_idx ON public.custody_transactions (invoice_id);

-- expose invoice_id through the custody effects view
CREATE OR REPLACE VIEW public.custody_txn_effects
WITH (security_invoker = true) AS
SELECT t.id,
    t.serial_no,
    t.supervisor_id,
    t.project_id,
    t.txn_type,
    t.amount,
    t.txn_date,
    t.status,
    t.reason,
    t.notes_ar,
    t.deleted_at,
    t.reversal_of_id,
    o.serial_no AS reversal_of_serial,
    o.txn_type AS reversal_of_type,
    r.id AS reversed_by_id,
    r.serial_no AS reversed_by_serial,
    (CASE
        WHEN t.txn_type = 'reversal'::custody_txn_type THEN - public.custody_base_effect(o.txn_type, t.amount)
        ELSE public.custody_base_effect(t.txn_type, t.amount)
     END)::numeric(14,2) AS signed_amount,
    t.invoice_id,
    o.invoice_id AS reversal_of_invoice_id
   FROM public.custody_transactions t
     LEFT JOIN public.custody_transactions o ON o.id = t.reversal_of_id
     LEFT JOIN public.custody_transactions r ON r.reversal_of_id = t.id AND r.deleted_at IS NULL;

-- settled amount = approved settlement effects tied to the invoice (reversals flip sign)
CREATE OR REPLACE FUNCTION public.invoice_settled_amount(p_invoice_id uuid)
RETURNS numeric
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
  SELECT coalesce(sum(-e.signed_amount), 0)
  FROM public.custody_txn_effects e
  WHERE coalesce(e.invoice_id, e.reversal_of_invoice_id) = p_invoice_id
    AND e.status = 'approved'
    AND e.deleted_at IS NULL
$$;
GRANT EXECUTE ON FUNCTION public.invoice_settled_amount(uuid) TO PUBLIC;

CREATE OR REPLACE FUNCTION public.custody_settlement_guard()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_total numeric;
  v_settled numeric;
  v_status public.record_status;
BEGIN
  IF NEW.invoice_id IS NULL THEN
    RETURN NEW;
  END IF;

  IF NOT public.is_accountant() THEN
    RAISE EXCEPTION 'settlement_requires_accountant';
  END IF;

  SELECT total_amount, status INTO v_total, v_status
  FROM public.invoices WHERE id = NEW.invoice_id;

  IF v_status IS DISTINCT FROM 'approved' THEN
    RAISE EXCEPTION 'settlement_requires_approved_invoice';
  END IF;

  IF NEW.txn_type = 'settlement' THEN
    SELECT public.invoice_settled_amount(NEW.invoice_id) INTO v_settled;
    IF v_settled + coalesce(NEW.amount, 0) > v_total + 0.005 THEN
      RAISE EXCEPTION 'settlement_exceeds_invoice_total';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER custody_settlement_guard_trg
  BEFORE INSERT ON public.custody_transactions
  FOR EACH ROW EXECUTE FUNCTION public.custody_settlement_guard();

-- expose invoice link + settlement summary
CREATE OR REPLACE VIEW public.invoice_settlements
WITH (security_invoker = true) AS
SELECT
  i.id AS invoice_id,
  i.total_amount,
  public.invoice_settled_amount(i.id) AS settled_amount,
  round(i.total_amount - public.invoice_settled_amount(i.id), 2) AS remaining_amount
FROM public.invoices i
WHERE i.deleted_at IS NULL;

GRANT SELECT ON public.invoice_settlements TO authenticated;
GRANT SELECT ON public.invoice_settlements TO service_role;