-- =========================================================
-- 1) SUPPLIERS
-- =========================================================
CREATE TABLE public.suppliers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name_ar text NOT NULL,
  name_en text,
  tax_number text,
  commercial_reg text,
  unified_number text,
  phone text,
  email text,
  city text,
  address text,
  notes text,
  is_active boolean NOT NULL DEFAULT true,
  created_by uuid,
  deleted_at timestamptz,
  delete_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT, INSERT, UPDATE ON public.suppliers TO authenticated;
GRANT ALL ON public.suppliers TO service_role;
ALTER TABLE public.suppliers ENABLE ROW LEVEL SECURITY;

CREATE UNIQUE INDEX suppliers_tax_number_unique
  ON public.suppliers (tax_number)
  WHERE tax_number IS NOT NULL AND btrim(tax_number) <> '' AND deleted_at IS NULL;

CREATE POLICY "suppliers_select_staff" ON public.suppliers
  FOR SELECT TO authenticated
  USING (public.is_accountant() OR public.has_role(auth.uid(), 'employee'));

CREATE POLICY "suppliers_insert_staff" ON public.suppliers
  FOR INSERT TO authenticated
  WITH CHECK (public.is_accountant() OR public.has_role(auth.uid(), 'employee'));

CREATE POLICY "suppliers_update_staff" ON public.suppliers
  FOR UPDATE TO authenticated
  USING (public.is_accountant() OR public.has_role(auth.uid(), 'employee'))
  WITH CHECK (public.is_accountant() OR public.has_role(auth.uid(), 'employee'));

CREATE TRIGGER suppliers_set_updated_at
  BEFORE UPDATE ON public.suppliers
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

-- =========================================================
-- 2) INVOICE NUMBER NORMALIZATION
-- =========================================================
CREATE OR REPLACE FUNCTION public.normalize_doc_no(p_value text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SECURITY INVOKER
SET search_path = public
AS $$
  SELECT nullif(
    upper(
      regexp_replace(
        translate(
          coalesce(p_value, ''),
          '٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹',
          '01234567890123456789'
        ),
        '[^0-9A-Za-z\u0621-\u064A]', '', 'g'
      )
    ),
    ''
  )
$$;
GRANT EXECUTE ON FUNCTION public.normalize_doc_no(text) TO PUBLIC;

-- =========================================================
-- 3) INVOICES
-- =========================================================
CREATE TABLE public.invoices (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  internal_no bigint GENERATED BY DEFAULT AS IDENTITY,
  supplier_id uuid NOT NULL REFERENCES public.suppliers(id),
  invoice_no text NOT NULL,
  invoice_no_norm text GENERATED ALWAYS AS (public.normalize_doc_no(invoice_no)) STORED,
  invoice_date date NOT NULL,
  project_id uuid NOT NULL REFERENCES public.projects(id),
  supervisor_id uuid REFERENCES public.supervisors(id),
  amount_before_tax numeric(14,2) NOT NULL DEFAULT 0,
  tax_amount numeric(14,2) NOT NULL DEFAULT 0,
  total_amount numeric(14,2) NOT NULL DEFAULT 0,
  description text,
  status public.record_status NOT NULL DEFAULT 'draft',
  duplicate_reason text,
  client_token text,
  created_by uuid,
  updated_by uuid,
  deleted_at timestamptz,
  delete_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT, INSERT, UPDATE ON public.invoices TO authenticated;
GRANT ALL ON public.invoices TO service_role;
ALTER TABLE public.invoices ENABLE ROW LEVEL SECURITY;

CREATE UNIQUE INDEX invoices_internal_no_unique ON public.invoices (internal_no);
CREATE UNIQUE INDEX invoices_client_token_unique ON public.invoices (client_token) WHERE client_token IS NOT NULL;

-- duplicate guard: same supplier + date + normalized number, unless the accountant
-- explicitly confirmed the duplicate with a reason
CREATE UNIQUE INDEX invoices_duplicate_guard
  ON public.invoices (supplier_id, invoice_date, invoice_no_norm)
  WHERE deleted_at IS NULL AND duplicate_reason IS NULL;

CREATE INDEX invoices_project_idx ON public.invoices (project_id);
CREATE INDEX invoices_supervisor_idx ON public.invoices (supervisor_id);
CREATE INDEX invoices_supplier_idx ON public.invoices (supplier_id);

CREATE POLICY "invoices_select_scoped" ON public.invoices
  FOR SELECT TO authenticated
  USING (public.is_accountant() OR public.can_access_project(project_id));

CREATE POLICY "invoices_insert_scoped" ON public.invoices
  FOR INSERT TO authenticated
  WITH CHECK (public.is_accountant() OR public.can_access_project(project_id));

CREATE POLICY "invoices_update_scoped" ON public.invoices
  FOR UPDATE TO authenticated
  USING (public.is_accountant() OR public.can_access_project(project_id))
  WITH CHECK (public.is_accountant() OR public.can_access_project(project_id));

CREATE TRIGGER invoices_set_updated_at
  BEFORE UPDATE ON public.invoices
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

-- totals + workflow guard
CREATE OR REPLACE FUNCTION public.invoices_guard()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_is_acc boolean := public.is_accountant();
BEGIN
  NEW.total_amount := round(coalesce(NEW.amount_before_tax, 0) + coalesce(NEW.tax_amount, 0), 2);

  IF TG_OP = 'INSERT' THEN
    IF NOT v_is_acc AND NEW.status NOT IN ('draft', 'under_review') THEN
      RAISE EXCEPTION 'employee_cannot_set_status';
    END IF;
    IF NEW.duplicate_reason IS NOT NULL AND NOT v_is_acc THEN
      RAISE EXCEPTION 'duplicate_override_requires_accountant';
    END IF;
    RETURN NEW;
  END IF;

  -- UPDATE
  IF NOT v_is_acc THEN
    IF OLD.status NOT IN ('draft', 'returned') THEN
      RAISE EXCEPTION 'employee_cannot_edit_locked_invoice';
    END IF;
    IF NEW.status NOT IN ('draft', 'under_review') THEN
      RAISE EXCEPTION 'employee_cannot_set_status';
    END IF;
    IF NEW.duplicate_reason IS DISTINCT FROM OLD.duplicate_reason THEN
      RAISE EXCEPTION 'duplicate_override_requires_accountant';
    END IF;
  END IF;

  -- an approved invoice's core fields can never change silently
  IF OLD.status = 'approved' AND NEW.status = 'approved' THEN
    IF NEW.supplier_id IS DISTINCT FROM OLD.supplier_id
       OR NEW.invoice_no IS DISTINCT FROM OLD.invoice_no
       OR NEW.invoice_date IS DISTINCT FROM OLD.invoice_date
       OR NEW.amount_before_tax IS DISTINCT FROM OLD.amount_before_tax
       OR NEW.tax_amount IS DISTINCT FROM OLD.tax_amount THEN
      RAISE EXCEPTION 'approved_invoice_is_locked';
    END IF;
  END IF;

  -- status change reasons
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    IF NEW.status IN ('returned', 'cancelled') AND coalesce(btrim(NEW.description), '') = '' AND TRUE THEN
      NULL; -- note is stored in invoice_status_history, validated there
    END IF;
    NEW.updated_by := auth.uid();
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER invoices_guard_trg
  BEFORE INSERT OR UPDATE ON public.invoices
  FOR EACH ROW EXECUTE FUNCTION public.invoices_guard();

